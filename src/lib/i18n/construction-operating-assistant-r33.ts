export type GoldenWorkflowCopyKey = keyof typeof GOLDEN_WORKFLOW_COPY["fr-CA"];

export function goldenWorkflowCopy(locale: GoldenWorkflowLocale, key: GoldenWorkflowCopyKey): string {
  return GOLDEN_WORKFLOW_COPY[locale][key];
}

export function assertGoldenWorkflowCopyComplete(): true {
  const french = Object.keys(GOLDEN_WORKFLOW_COPY["fr-CA"]).sort();
  const english = Object.keys(GOLDEN_WORKFLOW_COPY["en-CA"]).sort();
  if (JSON.stringify(french) !== JSON.stringify(english)) throw new Error("GOLDEN_WORKFLOW_COPY_INCOMPLETE");
  if (Object.values(GOLDEN_WORKFLOW_COPY).some((catalog) => Object.values(catalog).some((value) => !value.trim()))) throw new Error("GOLDEN_WORKFLOW_COPY_EMPTY");
  return true;
}
